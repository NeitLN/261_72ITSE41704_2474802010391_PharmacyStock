import { Type } from 'class-transformer';
import {
  ArrayMaxSize,
  ArrayMinSize,
  IsArray,
  IsInt,
  IsOptional,
  IsUUID,
  Max,
  Min,
  ValidateNested,
} from 'class-validator';

/**
 * One over-the-counter line: a medicine and how many base units. FEFO
 * chooses the batches (BR01); the client never names a batch.
 */
export class OtcLineDto {
  @IsUUID('4', { message: 'Choose a medicine.' })
  medicineId: string;

  @IsInt({ message: 'Quantity must be a whole number of base units.' })
  @Min(1, { message: 'Quantity must be at least 1.' })
  @Max(100_000)
  quantity: number;
}

/**
 * Body of `POST /sales` (UC07): the confirmed payment, the only point at
 * which an over-the-counter sale moves stock (FR-45, DEC-05). `requestId` is
 * generated by the client once per payment; a repeat returns the first
 * receipt (FR-23).
 */
export class SaleDto {
  @IsUUID('4', { message: 'Request ID must be a UUID.' })
  requestId: string;

  @IsArray()
  @ArrayMinSize(1, { message: 'Add at least one medicine to the sale.' })
  @ArrayMaxSize(50)
  @ValidateNested({ each: true })
  @Type(() => OtcLineDto)
  otcLines: OtcLineDto[];

  /** Optional: an over-the-counter sale need not identify the buyer. */
  @IsOptional()
  @IsUUID('4', { message: 'Choose a customer.' })
  customerId?: string;
}
