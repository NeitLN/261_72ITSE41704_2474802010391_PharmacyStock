import { PlusOutlined } from '@ant-design/icons';
import { App, Button, Drawer, Form, Input, Modal, Space, Table, Typography } from 'antd';
import type { ColumnsType } from 'antd/es/table';
import { useCallback, useState } from 'react';
import { type Customer, type CustomerInput, customersApi } from '../api/customers';
import { showApiError } from '../api/errors';
import { type PrescriptionSummary, prescriptionsApi } from '../api/prescriptions';
import { useLoad } from '../api/useLoad';
import { StatusTag } from '../ui/tags';

const NO_CUSTOMERS: Customer[] = [];
const NO_PRESCRIPTIONS: PrescriptionSummary[] = [];

/**
 * UC14 customers: search by name, code or phone, add and edit. The code is
 * generated by the backend and never edited; there is no deactivation
 * (UC14, open question).
 */
export function CustomersPanel() {
  const { message } = App.useApp();
  const [search, setSearch] = useState('');
  const [editing, setEditing] = useState<Customer | 'new' | null>(null);
  const [history, setHistory] = useState<Customer | null>(null);

  const fetchCustomers = useCallback(() => customersApi.list(search || undefined), [search]);
  const { data: customers, loading, reload } = useLoad(fetchCustomers, NO_CUSTOMERS);

  const columns: ColumnsType<Customer> = [
    { title: 'Code', dataIndex: 'code', width: 110 },
    { title: 'Full name', dataIndex: 'fullName' },
    { title: 'Phone', dataIndex: 'phone', width: 160, render: (v: string | null) => v ?? '—' },
    {
      title: 'Date of birth',
      dataIndex: 'dateOfBirth',
      width: 130,
      render: (v: string | null) => v ?? '—',
    },
    { title: 'Address', dataIndex: 'address', render: (v: string | null) => v ?? '—' },
    {
      title: '',
      key: 'actions',
      width: 180,
      render: (_, customer) => (
        <Space>
          <Button size="small" onClick={() => setEditing(customer)}>
            Edit
          </Button>
          <Button size="small" onClick={() => setHistory(customer)}>
            History
          </Button>
        </Space>
      ),
    },
  ];

  return (
    <>
      <Space style={{ width: '100%', justifyContent: 'flex-end' }} wrap>
        <Input.Search
          allowClear
          placeholder="Search name, code or phone"
          onSearch={(value) => setSearch(value.trim())}
          style={{ width: 280 }}
        />
        <Button type="primary" icon={<PlusOutlined />} onClick={() => setEditing('new')}>
          Add customer
        </Button>
      </Space>

      <Table
        rowKey="id"
        columns={columns}
        dataSource={customers}
        loading={loading}
        pagination={{ pageSize: 20, hideOnSinglePage: true }}
        locale={{
          emptyText: search ? 'No customer matches the search.' : 'No customers yet.',
        }}
        style={{ marginTop: 16 }}
      />

      <CustomerFormModal
        key={editing === 'new' ? 'new' : (editing?.id ?? 'closed')}
        customer={editing}
        onClose={() => setEditing(null)}
        onSaved={(saved) => {
          message.success(`${saved.fullName} (${saved.code}) saved.`);
          setEditing(null);
          reload();
        }}
      />

      {history && (
        <CustomerHistoryDrawer
          key={history.id}
          customer={history}
          onClose={() => setHistory(null)}
        />
      )}
    </>
  );
}

/** UC14: a customer's prescriptions, read-only. */
function CustomerHistoryDrawer({
  customer,
  onClose,
}: {
  customer: Customer;
  onClose: () => void;
}) {
  const fetchHistory = useCallback(
    () => prescriptionsApi.list({ customerId: customer.id }),
    [customer.id],
  );
  const { data: prescriptions, loading } = useLoad(fetchHistory, NO_PRESCRIPTIONS);

  return (
    <Drawer
      open
      title={`Prescriptions of ${customer.fullName}`}
      onClose={onClose}
      size={760}
    >
      <Typography.Text strong>
        {prescriptions.length} prescription{prescriptions.length === 1 ? '' : 's'}
      </Typography.Text>
      <Table
        rowKey="id"
        size="small"
        columns={[
          { title: 'Reference', dataIndex: 'referenceNumber', width: 150 },
          { title: 'Issued', dataIndex: 'issuedDate', width: 110 },
          { title: 'Prescriber', render: (_, p) => p.prescriber.fullName },
          { title: 'Items', dataIndex: 'itemCount', width: 70, align: 'right' },
          {
            title: 'Status',
            width: 160,
            render: (_, p) => <StatusTag kind="prescription" value={p.status} />,
          },
        ]}
        dataSource={prescriptions}
        loading={loading}
        pagination={false}
        locale={{ emptyText: 'No prescriptions for this customer yet.' }}
        style={{ marginTop: 12 }}
      />
    </Drawer>
  );
}

interface CustomerFormModalProps {
  /** The customer to edit, 'new' to add one, or null when closed. */
  customer: Customer | 'new' | null;
  onClose: () => void;
  onSaved: (saved: Customer) => void;
}

interface CustomerFormValues {
  fullName: string;
  phone?: string;
  dateOfBirth?: string;
  address?: string;
}

/** Remounted (via `key`) each time it opens, so it starts from the customer's values. */
function CustomerFormModal({ customer, onClose, onSaved }: CustomerFormModalProps) {
  const [form] = Form.useForm<CustomerFormValues>();
  const [saving, setSaving] = useState(false);
  const [formError, setFormError] = useState<string | null>(null);
  const isNew = customer === 'new';
  const initialValues: Partial<CustomerFormValues> =
    customer && customer !== 'new'
      ? {
          fullName: customer.fullName,
          phone: customer.phone ?? '',
          dateOfBirth: customer.dateOfBirth ?? '',
          address: customer.address ?? '',
        }
      : {};

  async function submit(values: CustomerFormValues) {
    if (!customer) return;
    setSaving(true);
    setFormError(null);
    try {
      const saved =
        customer === 'new'
          ? await customersApi.create({
              ...values,
              dateOfBirth: values.dateOfBirth || undefined,
            } satisfies CustomerInput)
          : // An emptied date of birth is cleared; phone and address clear as ''.
            await customersApi.update(customer.id, {
              ...values,
              dateOfBirth: values.dateOfBirth || null,
            });
      onSaved(saved);
    } catch (error) {
      setFormError(showApiError(form, error));
    } finally {
      setSaving(false);
    }
  }

  return (
    <Modal
      open={customer !== null}
      title={isNew ? 'Add customer' : `Edit customer ${customer?.code ?? ''}`}
      okText="Save"
      confirmLoading={saving}
      onOk={() => form.submit()}
      onCancel={onClose}
      forceRender
    >
      <Form form={form} layout="vertical" initialValues={initialValues} onFinish={submit} requiredMark>
        <Form.Item
          name="fullName"
          label="Full name"
          rules={[{ required: true, whitespace: true, message: 'Full name is required.' }]}
        >
          <Input maxLength={200} />
        </Form.Item>
        <Form.Item name="phone" label="Phone number">
          <Input maxLength={30} placeholder="e.g. 0909 123 456" />
        </Form.Item>
        <Form.Item name="dateOfBirth" label="Date of birth">
          <Input type="date" />
        </Form.Item>
        <Form.Item name="address" label="Address">
          <Input maxLength={300} />
        </Form.Item>
        <Typography.Paragraph type="secondary" style={{ marginBottom: 0 }}>
          The address and a date of birth (or an age on the prescription) are needed before a
          prescription for this customer can be dispensed (DEC-03).
        </Typography.Paragraph>
        {formError && <Typography.Text type="danger">{formError}</Typography.Text>}
      </Form>
    </Modal>
  );
}
