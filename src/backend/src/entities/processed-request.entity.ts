import {
  Column,
  CreateDateColumn,
  Entity,
  JoinColumn,
  ManyToOne,
  PrimaryColumn,
  type Relation,
} from 'typeorm';
import { User } from './user.entity.js';

/**
 * A stock command that has already been carried out (FR-23).
 *
 * The client sends a request ID with every dispensing, sale and return. The
 * row is written in the same transaction as the command, so a repeated request
 * finds it and gets the first result back without changing anything, and the
 * same ID with a different payload is refused. This is infrastructure for the
 * services, not a domain class.
 */
@Entity('processed_requests')
export class ProcessedRequest {
  /** Generated by the client, one per user action. */
  @PrimaryColumn({ type: 'uuid' })
  requestId: string;

  /** e.g. `dispense`, `sale`, `return`. */
  @Column()
  commandType: string;

  /** SHA-256 of the normalised payload, to detect a reused ID with other content. */
  @Column({ type: 'char', length: 64 })
  payloadHash: string;

  /** What the first execution returned, replayed on a repeat. */
  @Column({ type: 'jsonb' })
  result: unknown;

  @ManyToOne(() => User, { nullable: false })
  @JoinColumn({ name: 'user_id' })
  user: Relation<User>;

  @CreateDateColumn({ type: 'timestamptz' })
  createdAt: Date;
}
