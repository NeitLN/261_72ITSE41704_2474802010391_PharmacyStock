import { Type } from 'class-transformer';
import {
  ArrayMaxSize,
  ArrayMinSize,
  IsArray,
  IsDefined,
  IsInt,
  IsOptional,
  IsUUID,
  Max,
  Min,
  ValidateIf,
  ValidateNested,
} from 'class-validator';

/**
 * One over-the-counter line: a medicine and how many base units. FEFO
 * chooses the batches (BR01); the client never names a batch.
 */
export class OtcLineDto {
  @IsUUID('4', { message: 'Choose a medicine.' })
  medicineId: string;

  @IsInt({ message: 'Quantity must be a whole number of base units.' })
  @Min(1, { message: 'Quantity must be at least 1.' })
  @Max(100_000)
  quantity: number;
}

/**
 * Body of `POST /sales` (UC07): the confirmed payment. Over-the-counter lines
 * move stock now (FR-45); billing a prescription records the money for what
 * was handed over in UC06 and moves nothing (DEC-05, FR-26). At least one of
 * the two is required, reported on `otcLines` with the other field errors.
 * `requestId` is generated by
 * the client once per payment; a repeat returns the first receipt (FR-23).
 */
export class SaleDto {
  @IsUUID('4', { message: 'Request ID must be a UUID.' })
  requestId: string;

  // Required unless a prescription is billed; validated whenever it is sent.
  @ValidateIf((dto: SaleDto) => dto.otcLines !== undefined || !dto.prescriptionId)
  @IsDefined({ message: 'Add a medicine or choose a prescription to bill.' })
  @IsArray()
  @ArrayMinSize(1, { message: 'Add at least one medicine to the sale.' })
  @ArrayMaxSize(50)
  @ValidateNested({ each: true })
  @Type(() => OtcLineDto)
  otcLines?: OtcLineDto[];

  /** Bill every dispense line of this prescription not billed yet. */
  @IsOptional()
  @IsUUID('4', { message: 'Choose a prescription.' })
  prescriptionId?: string;

  /** Optional: an over-the-counter sale need not identify the buyer. */
  @IsOptional()
  @IsUUID('4', { message: 'Choose a customer.' })
  customerId?: string;
}
