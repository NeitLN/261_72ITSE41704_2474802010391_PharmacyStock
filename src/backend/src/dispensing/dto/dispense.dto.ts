import { Type } from 'class-transformer';
import {
  ArrayMaxSize,
  ArrayMinSize,
  IsArray,
  IsInt,
  IsOptional,
  IsString,
  IsUUID,
  Max,
  MaxLength,
  Min,
  ValidateNested,
} from 'class-validator';
import { TrimToNull } from '../../common/transforms.js';

/**
 * How much of one prescription item to hand over now. FEFO chooses the
 * batches (BR01); the client never names a batch.
 */
export class DispenseItemDto {
  @IsUUID('4', { message: 'Choose a prescription item.' })
  prescriptionItemId: string;

  @IsInt({ message: 'Quantity must be a whole number of base units.' })
  @Min(1, { message: 'Quantity must be at least 1.' })
  @Max(100_000)
  quantity: number;

  /**
   * Required when this hand-over leaves part of the item outstanding: the
   * pharmacist confirms the effect on the treatment was assessed and
   * discussed with the customer (DEC-02, FR-18). Checked in the service.
   */
  @IsOptional()
  @TrimToNull()
  @IsString()
  @MaxLength(500)
  partialSupplyNote?: string | null;
}

/**
 * Body of `POST /dispensings/preview`: what FEFO would issue now, with expiry
 * warnings and shortages. Nothing is locked, moved or reserved (DEC-05).
 */
export class DispensePreviewDto {
  @IsUUID('4', { message: 'Choose a prescription.' })
  prescriptionId: string;

  @IsArray()
  @ArrayMinSize(1, { message: 'Choose at least one item to dispense.' })
  @ArrayMaxSize(50)
  @ValidateNested({ each: true })
  @Type(() => DispenseItemDto)
  items: DispenseItemDto[];
}

/**
 * Body of `POST /dispensings`: the confirmed hand-over, the only point at
 * which stock leaves (FR-45). `requestId` is generated by the client once per
 * confirmation; a repeat returns the first result (FR-23).
 */
export class DispenseDto extends DispensePreviewDto {
  @IsUUID('4', { message: 'Request ID must be a UUID.' })
  requestId: string;
}
