import { Type } from 'class-transformer';
import {
  ArrayMaxSize,
  ArrayMinSize,
  IsArray,
  IsInt,
  IsNotEmpty,
  IsString,
  IsUUID,
  Max,
  MaxLength,
  Min,
  ValidateNested,
} from 'class-validator';
import { Trim } from '../../common/transforms.js';

/** One returned line: a line of the sale and how many base units come back. */
export class ReturnLineDto {
  @IsUUID('4', { message: 'Choose a line of the sale.' })
  saleLineId: string;

  @IsInt({ message: 'Quantity must be a whole number of base units.' })
  @Min(1, { message: 'Quantity must be at least 1.' })
  @Max(100_000)
  quantity: number;
}

/**
 * Body of `POST /returns` (UC08). `requestId` is generated by the client once
 * per return; a repeat returns the first result (FR-23). How many units a
 * line can take back is checked against the sale, not here (FR-27).
 */
export class ReturnDto {
  @IsUUID('4', { message: 'Request ID must be a UUID.' })
  requestId: string;

  @IsUUID('4', { message: 'Choose the sale to return against.' })
  saleId: string;

  @Trim()
  @IsString()
  @IsNotEmpty({ message: 'Say why the goods are returned.' })
  @MaxLength(500)
  reason: string;

  @IsArray()
  @ArrayMinSize(1, { message: 'Add at least one line to return.' })
  @ArrayMaxSize(50)
  @ValidateNested({ each: true })
  @Type(() => ReturnLineDto)
  lines: ReturnLineDto[];
}
