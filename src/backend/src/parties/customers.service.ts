import { Injectable } from '@nestjs/common';
import { InjectRepository } from '@nestjs/typeorm';
import type { Repository } from 'typeorm';
import { type Actor, assertPermission } from '../auth/actor.js';
import { Permission } from '../auth/permissions.js';
import { NotFound, ValidationFailed } from '../common/errors.js';
import { likePattern } from '../common/transforms.js';
import { Customer } from '../entities/index.js';
import { Clock } from '../stock/clock.js';
import type {
  CreateCustomerDto,
  ListCustomersQuery,
  UpdateCustomerDto,
} from './dto/customer.dto.js';

/**
 * Customers (patients) for prescription intake (FR-15, UC05 quick-create).
 * The customer code is generated by the service; the client never sends it.
 */
@Injectable()
export class CustomersService {
  constructor(
    @InjectRepository(Customer)
    private readonly customers: Repository<Customer>,
    private readonly clock: Clock,
  ) {}

  async list(actor: Actor, query: ListCustomersQuery): Promise<Customer[]> {
    assertPermission(actor, Permission.PRESCRIPTION_MANAGE);

    const qb = this.customers
      .createQueryBuilder('c')
      .orderBy('c.fullName', 'ASC')
      .limit(50);
    if (query.search) {
      qb.andWhere(
        '(c.fullName ILIKE :pattern OR c.code ILIKE :pattern OR c.phone ILIKE :pattern)',
        { pattern: likePattern(query.search) },
      );
    }
    return qb.getMany();
  }

  async get(actor: Actor, id: string): Promise<Customer> {
    assertPermission(actor, Permission.PRESCRIPTION_MANAGE);
    return this.findOrFail(id);
  }

  async create(actor: Actor, dto: CreateCustomerDto): Promise<Customer> {
    assertPermission(actor, Permission.PRESCRIPTION_MANAGE);
    this.checkDateOfBirth(dto.dateOfBirth);
    // The entity types predate the nullable columns (do not edit entities
    // per ticket), so nulls are carried through one cast; the database
    // columns are nullable and store NULL.
    const customer = this.customers.create({
      code: await this.nextCode(),
      fullName: dto.fullName,
      phone: dto.phone ?? null,
      dateOfBirth: dto.dateOfBirth ?? null,
      address: dto.address ?? null,
    } as unknown as Customer);
    // Two requests racing for the same code: the unique index answers with
    // 23505, translated by AllExceptionsFilter into a 409. No extra handling.
    return this.customers.save(customer);
  }

  async update(
    actor: Actor,
    id: string,
    dto: UpdateCustomerDto,
  ): Promise<Customer> {
    assertPermission(actor, Permission.PRESCRIPTION_MANAGE);
    await this.findOrFail(id);
    if (dto.dateOfBirth !== undefined) {
      this.checkDateOfBirth(dto.dateOfBirth);
    }
    // Write only the columns the request sent, so a concurrent change to
    // another column is never overwritten by a stale copy. The code is
    // generated and can never change through this endpoint.
    const changes: Partial<Customer> = {};
    if (dto.fullName !== undefined) changes.fullName = dto.fullName;
    // Same entity-typing cast as in create: null clears the column.
    if (dto.phone !== undefined)
      changes.phone = dto.phone as unknown as string;
    if (dto.dateOfBirth !== undefined)
      changes.dateOfBirth = dto.dateOfBirth as unknown as string;
    if (dto.address !== undefined)
      changes.address = dto.address as unknown as string;
    if (Object.keys(changes).length > 0) {
      await this.customers.update({ id }, changes);
    }
    return this.findOrFail(id);
  }

  /** The next code is one above the highest `KHnnnn` code in use. */
  private async nextCode(): Promise<string> {
    const latest = await this.customers
      .createQueryBuilder('c')
      .select('c.code', 'code')
      .orderBy('c.code', 'DESC')
      .limit(1)
      .getRawOne<{ code?: string }>();
    const highest = Number.parseInt(
      latest?.code?.replace(/^KH0*/, '') ?? '0',
      10,
    );
    return `KH${String((Number.isNaN(highest) ? 0 : highest) + 1).padStart(4, '0')}`;
  }

  private checkDateOfBirth(dateOfBirth: string | null | undefined): void {
    if (dateOfBirth != null && dateOfBirth > this.clock.today()) {
      throw ValidationFailed.field(
        'dateOfBirth',
        'Date of birth cannot be in the future.',
      );
    }
  }

  private async findOrFail(id: string): Promise<Customer> {
    const customer = await this.customers.findOneBy({ id });
    if (!customer) throw new NotFound('Customer', id);
    return customer;
  }
}
